"use strict";

// The panel's <script> lists, generated from the `PhComposerUI.define` declarations (html/module.js).
// Each panel file runs in a vm whose `PhComposerUI.define` only records its name and dependencies, so
// the graph is read by the registry's own entry point rather than by a second parser, and the order
// is the registry's own `PhComposerUI.order()`.
//
// Every page that loads the panel lists its modules between the markers below: the shipped
// index.html, and development pages that load the same panel from outside the extension folder.
// A development page also copies index.html's stylesheets and body markup, so it cannot drift from
// the panel it stands in for.
//
//   node tools/panel_manifest.js           fail when any page is stale
//   node tools/panel_manifest.js --write   rewrite every page between its markers

var fs = require("fs");
var path = require("path");
var vm = require("vm");

var panelFiles = require("../tests/support/panel_files");

var BEGIN = "<!-- panel-modules:begin (generated by tools/panel_manifest.js) -->";
var END = "<!-- panel-modules:end -->";
var STYLES_BEGIN = "<!-- panel-styles:begin (generated by tools/panel_manifest.js) -->";
var STYLES_END = "<!-- panel-styles:end -->";
var MARKUP_BEGIN = "<!-- panel-markup:begin (generated by tools/panel_manifest.js) -->";
var MARKUP_END = "<!-- panel-markup:end -->";
var INDENT = "    ";
var INDEX = path.join(panelFiles.html, "index.html");

/* The development pages, each with the path from the page to html/. */
var DEVELOPMENT_PAGES = [
  { path: path.join(panelFiles.root, "tools", "ui-preview", "index.html"), prefix: "../../src/ph_composer/html/" }
];

/* Shipped pages other than the panel, each in its own folder under html/ with an entry module. A page loads
   its entry and what that needs from the shared kit; the panel never loads a page's own modules. */
var PAGES = [
  { path: path.join(panelFiles.html, "agent_access", "index.html"), folder: "agent_access/",
    entry: "agent_access/page", prefix: "../" }
];

function moduleName(file) {
  return path.relative(panelFiles.html, file).split(path.sep).join("/").replace(/\.js$/, "");
}

/* { order: [name], definitions: { name: { file, dependencies } } } for the panel's modules, or with
   `withPages` for every module under html/, the other pages' own included. */
function graph(withPages) {
  var context = { window: {} };
  var definitions = {};
  vm.runInNewContext(fs.readFileSync(path.join(panelFiles.html, "module.js"), "utf8"), context);
  var registry = context.window.PhComposerUI;
  panelFiles.panelFiles().forEach(function (file) {
    var name = moduleName(file);
    if (name === "module" || (!withPages && pageModule(name))) return;
    var declared = [];
    context.PhComposerUI = {
      define: function (defined, dependencies, factory) {
        declared.push(defined);
        registry.define(defined, dependencies, factory);
        definitions[defined] = { file: file, dependencies: dependencies.slice() };
      }
    };
    vm.runInNewContext(fs.readFileSync(file, "utf8"), context, { filename: file });
    if (declared.length !== 1 || declared[0] !== name) {
      throw new Error(path.relative(panelFiles.root, file) + " must make exactly one PhComposerUI.define(\"" + name +
        "\", ...) call; found " + JSON.stringify(declared));
    }
  });
  return { order: registry.order(), definitions: definitions };
}

/* Whether `name` belongs to a page other than the panel. */
function pageModule(name) {
  return PAGES.some(function (page) { return name.indexOf(page.folder) === 0; });
}

/* The modules `entry` needs, itself included, in `order`. */
function closure(order, definitions, entry) {
  var needed = Object.create(null);
  (function visit(name) {
    if (needed[name]) return;
    needed[name] = true;
    definitions[name].dependencies.forEach(visit);
  })(entry);
  return order.filter(function (name) { return needed[name]; });
}

function scriptTags(order, prefix) {
  return order.map(function (name) {
    return INDENT + "<script src=\"" + (prefix || "") + name + ".js\"></script>";
  }).join("\n");
}

function between(markup, begin, end, body) {
  var from = markup.indexOf(begin), to = markup.indexOf(end);
  if (from === -1 || to === -1 || to < from) throw new Error("page has no " + begin + " ... " + end + " markers");
  return markup.slice(0, from + begin.length) + "\n" + body + "\n" + INDENT + markup.slice(to);
}

/* `prefix` is the path from the page to html/; index.html needs none. */
function render(markup, order, prefix) {
  return between(markup, BEGIN, END, scriptTags(order, prefix));
}

/* A development page with index.html's stylesheets, body markup and module list. */
function renderDevelopmentPage(page, index, order, prefix) {
  var styles = [], body = /<body[^>]*>/.exec(index), markup;
  index.replace(/<link rel="stylesheet" href="([^"]+)">/g, function (tag, href) {
    styles.push(INDENT + "<link rel=\"stylesheet\" href=\"" + prefix + href + "\">");
    return tag;
  });
  markup = index.slice(body.index + body[0].length, index.indexOf("<script")).replace(/^\n+|\s+$/g, "");
  page = between(page, STYLES_BEGIN, STYLES_END, styles.join("\n"));
  page = between(page, MARKUP_BEGIN, MARKUP_END, markup);
  return render(page, order, prefix);
}

function main() {
  var write = process.argv.indexOf("--write") !== -1;
  var order = graph().order, modules = graph(true);
  var index = fs.readFileSync(INDEX, "utf8");
  var pages = [[INDEX, index, render(index, order)]];
  DEVELOPMENT_PAGES.forEach(function (entry) {
    var page = fs.readFileSync(entry.path, "utf8");
    pages.push([entry.path, page, renderDevelopmentPage(page, pages[0][2], order, entry.prefix)]);
  });
  PAGES.forEach(function (entry) {
    var page = fs.readFileSync(entry.path, "utf8");
    var needed = closure(modules.order, modules.definitions, entry.entry);
    pages.push([entry.path, page, render(page, needed, entry.prefix)]);
  });
  var stale = pages.filter(function (page) { return page[1] !== page[2]; });
  if (write) {
    stale.forEach(function (page) { fs.writeFileSync(page[0], page[2]); });
    console.log("panel manifest: " + stale.length + " of " + pages.length + " pages rewritten");
  } else if (stale.length) {
    stale.forEach(function (page) {
      console.error(path.relative(panelFiles.root, page[0]) +
        " is stale; run 'make panel-manifest' and commit the result");
    });
    process.exit(1);
  } else {
    console.log("Panel manifest up to date: " + order.length + " modules, " + pages.length + " pages");
  }
}

module.exports = { graph: graph, render: render, renderDevelopmentPage: renderDevelopmentPage,
  pageModule: pageModule, closure: closure, DEVELOPMENT_PAGES: DEVELOPMENT_PAGES, PAGES: PAGES, BEGIN: BEGIN,
  END: END };

if (require.main === module) main();
